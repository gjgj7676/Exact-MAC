`timescale 1ns/1ps

module tb_mac_exact;

    //-------------------------------------------------
    // Testbench Signals
    //-------------------------------------------------

    logic        clk;
    logic        rst;

    logic [7:0]  A;
    logic [7:0]  B;

    logic [15:0] Acc;
    logic        Overflow;

    //-------------------------------------------------
    // Instantiate DUT
    //-------------------------------------------------

    mac_exact DUT (

        .clk(clk),
        .rst(rst),

        .A(A),
        .B(B),

        .Acc(Acc),
        .Overflow(Overflow)

    );

    //-------------------------------------------------
    // Clock Generation (10 ns Period)
    //-------------------------------------------------

    initial begin
        clk = 0;
        forever #5 clk = ~clk;
    end

    //-------------------------------------------------
    // Test Sequence
    //-------------------------------------------------

    initial begin

        $dumpfile("waves/mac_exact.vcd");
        $dumpvars(0, tb_mac_exact);

        //---------------------------------------------
        // Reset
        //---------------------------------------------

        rst = 1;
        A   = 0;
        B   = 0;

        #10;

        rst = 0;

        //---------------------------------------------
        // Cycle 1
        // 3 × 4 = 12
        //---------------------------------------------

        A = 8'd3;
        B = 8'd4;

        #10;

        //---------------------------------------------
        // Cycle 2
        // + (2 × 5) = 10
        //---------------------------------------------

        A = 8'd2;
        B = 8'd5;

        #10;

        //---------------------------------------------
        // Cycle 3
        // + (7 × 8) = 56
        //---------------------------------------------

        A = 8'd7;
        B = 8'd8;

        #10;

        //---------------------------------------------
        // Cycle 4
        // + (10 × 2) = 20
        //---------------------------------------------

        A = 8'd10;
        B = 8'd2;

        #10;

        //---------------------------------------------
        // Cycle 5
        // + (15 × 15) = 225
        //---------------------------------------------

        A = 8'd15;
        B = 8'd15;

        #10;

        $finish;

    end

    //-------------------------------------------------
    // Monitor
    //-------------------------------------------------

    initial begin

        $monitor(
        "Time=%0t clk=%b rst=%b A=%0d B=%0d Acc=%0d Overflow=%b",
        $time, clk, rst, A, B, Acc, Overflow
        );

    end

endmodule